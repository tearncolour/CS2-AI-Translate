using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Colossal.PSI.Environment;
using Newtonsoft.Json;

namespace AITranslate.Core
{
    /// <summary>
    /// 译文持久化，目录本身就是一个 I18N Everywhere 语言包：
    ///   ModsData/AITranslateLocalization/
    ///     i18n.json                             语言包描述（I18N 据此识别）
    ///     Localization/&lt;locale&gt;/&lt;mod&gt;.json     译文（key → 译文），由 I18N 加载
    ///     FallbackLocale/&lt;locale&gt;/&lt;mod&gt;.json   游戏回退语言（en-US）的译文，只由本 mod 注入
    ///     Sources/&lt;locale&gt;/&lt;mod&gt;.json          翻译时的原文，用于检测 mod 更新后需要重翻的条目
    ///     mods.json                             mod 键 → 显示名，便于人工查阅
    /// 即使以后停用本 mod，I18N Everywhere 仍会继续加载 Localization 下的译文。
    /// 英语译文不能放进 Localization/en-US：I18N 会把它当作所有语言的回退文本，
    /// 导致中文游戏里中文作者写的 mod 原文被英文机翻顶替。
    /// </summary>
    internal sealed class TranslationStore
    {
        // I18N 只把名字以 "Localization" 结尾的 ModsData 子目录当作语言包。
        public const string kPackFolderName = "AITranslateLocalization";

        // 改名前（I18N Auto Translate）使用的目录，启动时自动迁移。
        private const string kLegacyPackFolderName = "I18NAutoTranslateLocalization";

        private static readonly Encoding s_Utf8 = new UTF8Encoding(false);

        internal sealed class ModTranslations
        {
            public readonly Dictionary<string, string> Translations = new Dictionary<string, string>(StringComparer.Ordinal);
            public readonly Dictionary<string, string> Sources = new Dictionary<string, string>(StringComparer.Ordinal);

            /// <summary>AI 审校评分（1~5）；未审校的条目没有记录。</summary>
            public readonly Dictionary<string, int> Scores = new Dictionary<string, int>(StringComparer.Ordinal);
        }

        // locale → modKey → data
        // 检测在后台线程读取存储，界面在主线程读取；懒加载和增删分组时加锁。
        private readonly object m_Lock = new object();

        private readonly Dictionary<string, Dictionary<string, ModTranslations>> m_Data = new Dictionary<string, Dictionary<string, ModTranslations>>(StringComparer.OrdinalIgnoreCase);

        private Dictionary<string, string> m_Names = new Dictionary<string, string>(StringComparer.Ordinal);

        public string RootDir { get; }

        public string LocalizationDir => Path.Combine(RootDir, "Localization");

        private string FallbackDir => Path.Combine(RootDir, "FallbackLocale");

        private string SourcesDir => Path.Combine(RootDir, "Sources");

        /// <summary>游戏的回退语言（en-US）。</summary>
        public string FallbackLocale { get; set; } = "en-US";

        public TranslationStore()
        {
            RootDir = Path.Combine(EnvPath.kUserDataPath, "ModsData", kPackFolderName);
        }

        /// <summary>把旧名称目录中的译文合并到新目录（已存在的同名文件不覆盖），然后删除旧目录。</summary>
        public void MigrateLegacy()
        {
            string legacy = Path.Combine(EnvPath.kUserDataPath, "ModsData", kLegacyPackFolderName);
            if (!Directory.Exists(legacy))
            {
                return;
            }
            int moved = 0;
            foreach (string file in Directory.GetFiles(legacy, "*", SearchOption.AllDirectories))
            {
                string relative = file.Substring(legacy.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
                if (relative.Equals("i18n.json", StringComparison.OrdinalIgnoreCase) || relative.EndsWith(".tmp", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }
                string target = Path.Combine(RootDir, relative);
                if (File.Exists(target))
                {
                    continue;
                }
                Directory.CreateDirectory(Path.GetDirectoryName(target));
                File.Copy(file, target);
                moved++;
            }
            Directory.Delete(legacy, recursive: true);
            Mod.Log.Info($"Migrated {moved} files from {legacy}");
        }

        public void EnsureLayout()
        {
            Directory.CreateDirectory(LocalizationDir);
            Directory.CreateDirectory(SourcesDir);
            string info = Path.Combine(RootDir, "i18n.json");
            var pack = new Dictionary<string, string>
            {
                ["Name"] = "AI Translate!",
                ["IncludedLanguage"] = "auto",
                ["Author"] = "MeroT",
                ["Description"] = "Machine translations generated by AI Translate!. Delete a file to translate that mod again.",
            };
            string content = JsonConvert.SerializeObject(pack, Formatting.Indented);
            if (!File.Exists(info) || File.ReadAllText(info, s_Utf8) != content)
            {
                WriteAtomic(info, content);
            }
            string names = Path.Combine(RootDir, "mods.json");
            if (File.Exists(names))
            {
                try
                {
                    m_Names = JsonConvert.DeserializeObject<Dictionary<string, string>>(File.ReadAllText(names, s_Utf8))
                        ?? new Dictionary<string, string>(StringComparer.Ordinal);
                }
                catch (Exception ex)
                {
                    Mod.Log.Warn("mods.json unreadable: " + ex.Message);
                }
            }
        }

        /// <summary>丢弃内存缓存，下次访问时重新从磁盘读取（用于玩家手动修改译文文件后）。</summary>
        public void ClearCache()
        {
            lock (m_Lock)
            {
                m_Data.Clear();
            }
        }

        /// <summary>
        /// AI 生成的资产描述单独存放在 "desc_&lt;mod&gt;" 文件里，与译文分开，
        /// 不会被译文的清理/归属逻辑误删，也能单独删除重新生成。
        /// </summary>
        public static string DescriptionGroup(string modKey) => "desc_" + modKey;

        private string KnownModsPath => Path.Combine(RootDir, "known_mods.json");

        /// <summary>
        /// 已见过的 mod 列表，用来判断哪些 mod 是新安装的。文件不存在时返回 null（首次运行）。
        /// </summary>
        public HashSet<string> LoadKnownMods()
        {
            try
            {
                if (!File.Exists(KnownModsPath))
                {
                    return null;
                }
                var list = JsonConvert.DeserializeObject<List<string>>(File.ReadAllText(KnownModsPath, s_Utf8));
                return new HashSet<string>(list ?? new List<string>(), StringComparer.Ordinal);
            }
            catch (Exception ex)
            {
                Mod.Log.Warn("known_mods.json unreadable: " + ex.Message);
                return null;
            }
        }

        public void SaveKnownMods(IEnumerable<string> keys)
        {
            Directory.CreateDirectory(RootDir);
            WriteAtomic(KnownModsPath, JsonConvert.SerializeObject(keys.OrderBy(k => k, StringComparer.Ordinal).ToList(), Formatting.Indented));
        }

        private string BuildingPhrasesPath(string locale) => Path.Combine(RootDir, "BuildingTypes", locale + ".json");

        /// <summary>
        /// 区域建筑类型短语的译名缓存（"CN Residential Low" → "中国低层住宅"）。所有同类建筑共用，
        /// 玩家也可以直接编辑这个文件统一修正某类建筑的叫法。
        /// </summary>
        public Dictionary<string, string> LoadBuildingPhrases(string locale)
        {
            try
            {
                string path = BuildingPhrasesPath(locale);
                if (File.Exists(path))
                {
                    return JsonConvert.DeserializeObject<Dictionary<string, string>>(File.ReadAllText(path, s_Utf8))
                        ?? new Dictionary<string, string>(StringComparer.Ordinal);
                }
            }
            catch (Exception ex)
            {
                Mod.Log.Warn("Building type cache unreadable: " + ex.Message);
            }
            return new Dictionary<string, string>(StringComparer.Ordinal);
        }

        public void SaveBuildingPhrases(string locale, Dictionary<string, string> phrases)
        {
            string path = BuildingPhrasesPath(locale);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            WriteAtomic(path, JsonConvert.SerializeObject(Sorted(phrases), Formatting.Indented));
        }

        public static string FileNameFor(string modKey)
        {
            string name = Regex.Replace(modKey ?? "unknown", @"[^A-Za-z0-9_\-.]", "_");
            return name.Length > 120 ? name.Substring(0, 120) : name;
        }

        private string TranslationDir(string locale) => Path.Combine(IsFallback(locale) ? FallbackDir : LocalizationDir, locale);

        private bool IsFallback(string locale) => string.Equals(locale, FallbackLocale, StringComparison.OrdinalIgnoreCase);

        private string TranslationPath(string locale, string modKey) => Path.Combine(TranslationDir(locale), FileNameFor(modKey) + ".json");

        private string SourcePath(string locale, string modKey) => Path.Combine(SourcesDir, locale, FileNameFor(modKey) + ".json");

        private string QualityPath(string locale, string modKey) => Path.Combine(RootDir, "Quality", locale, FileNameFor(modKey) + ".json");

        public Dictionary<string, ModTranslations> GetLocale(string locale)
        {
            lock (m_Lock)
            {
                if (m_Data.TryGetValue(locale, out var map))
                {
                    return map;
                }
                map = new Dictionary<string, ModTranslations>(StringComparer.Ordinal);
                m_Data[locale] = map;

                string dir = TranslationDir(locale);
                if (!Directory.Exists(dir))
                {
                    return map;
                }
                foreach (string file in Directory.GetFiles(dir, "*.json"))
                {
                    string key = Path.GetFileNameWithoutExtension(file);
                    var data = new ModTranslations();
                    try
                    {
                        Fill(data.Translations, file);
                        string src = SourcePath(locale, key);
                        if (File.Exists(src))
                        {
                            Fill(data.Sources, src);
                        }
                        string quality = QualityPath(locale, key);
                        if (File.Exists(quality))
                        {
                            var scores = JsonConvert.DeserializeObject<Dictionary<string, int>>(File.ReadAllText(quality, s_Utf8));
                            if (scores != null)
                            {
                                foreach (var kv in scores)
                                {
                                    data.Scores[kv.Key] = kv.Value;
                                }
                            }
                        }
                    }
                    catch (Exception ex)
                    {
                        Mod.Log.Warn("Failed to read " + file + ": " + ex.Message);
                        continue;
                    }
                    map[key] = data;
                }
                return map;
            }
        }

        private static void Fill(Dictionary<string, string> target, string file)
        {
            var dict = JsonConvert.DeserializeObject<Dictionary<string, string>>(File.ReadAllText(file, s_Utf8));
            if (dict == null)
            {
                return;
            }
            foreach (var kv in dict)
            {
                if (kv.Key != null && kv.Value != null)
                {
                    target[kv.Key] = kv.Value;
                }
            }
        }

        public ModTranslations Get(string locale, string modKey)
        {
            lock (m_Lock)
            {
                GetLocale(locale).TryGetValue(FileNameFor(modKey), out var data);
                return data;
            }
        }

        public ModTranslations GetOrCreate(string locale, string modKey)
        {
            lock (m_Lock)
            {
                var map = GetLocale(locale);
                string file = FileNameFor(modKey);
                if (!map.TryGetValue(file, out var data))
                {
                    data = new ModTranslations();
                    map[file] = data;
                }
                return data;
            }
        }

        /// <summary>修正官方/自带译文中英混杂的结果单独存放在 "fix_&lt;mod&gt;"（原文记录的是被修正的那条译文）。</summary>
        public static string FixGroup(string modKey) => "fix_" + modKey;

        /// <summary>本 mod 翻译的译文（不含生成的描述和对官方译文的修正）。</summary>
        public Dictionary<string, string> GetOwnTranslations(string locale)
        {
            lock (m_Lock)
            {
                var all = new Dictionary<string, string>(StringComparer.Ordinal);
                foreach (var group in GetLocale(locale))
                {
                    if (group.Key.StartsWith("fix_", StringComparison.Ordinal) || group.Key.StartsWith("desc_", StringComparison.Ordinal))
                    {
                        continue;
                    }
                    foreach (var kv in group.Value.Translations)
                    {
                        all[kv.Key] = kv.Value;
                    }
                }
                return all;
            }
        }

        /// <summary>key → 存有它的译文分组（不含描述和混杂修正分组）。用于判断某个 key 是否已在别处翻译过。</summary>
        public Dictionary<string, string> TranslationGroups(string locale)
        {
            lock (m_Lock)
            {
                var map = new Dictionary<string, string>(StringComparer.Ordinal);
                foreach (var group in GetLocale(locale))
                {
                    if (group.Key.StartsWith("fix_", StringComparison.Ordinal) || group.Key.StartsWith("desc_", StringComparison.Ordinal))
                    {
                        continue;
                    }
                    foreach (string key in group.Value.Translations.Keys)
                    {
                        if (!map.ContainsKey(key))
                        {
                            map[key] = group.Key;
                        }
                    }
                }
                return map;
            }
        }

        /// <summary>当前语言下所有 mod 的译文合集（后写入的覆盖先写入的）。</summary>
        public Dictionary<string, string> GetAllTranslations(string locale)
        {
            lock (m_Lock)
            {
                var all = new Dictionary<string, string>(StringComparer.Ordinal);
                foreach (var data in GetLocale(locale).Values)
                {
                    foreach (var kv in data.Translations)
                    {
                        all[kv.Key] = kv.Value;
                    }
                }
                return all;
            }
        }

        public void Save(string locale, string modKey, string displayName)
        {
            var data = Get(locale, modKey);
            if (data == null)
            {
                return;
            }
            Directory.CreateDirectory(TranslationDir(locale));
            Directory.CreateDirectory(Path.Combine(SourcesDir, locale));
            WriteAtomic(TranslationPath(locale, modKey), JsonConvert.SerializeObject(Sorted(data.Translations), Formatting.Indented));
            WriteAtomic(SourcePath(locale, modKey), JsonConvert.SerializeObject(Sorted(data.Sources), Formatting.Indented));
            if (data.Scores.Count > 0)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(QualityPath(locale, modKey)));
                var scores = new SortedDictionary<string, int>(data.Scores.Where(kv => data.Translations.ContainsKey(kv.Key)).ToDictionary(kv => kv.Key, kv => kv.Value), StringComparer.Ordinal);
                WriteAtomic(QualityPath(locale, modKey), JsonConvert.SerializeObject(scores, Formatting.Indented));
            }

            if (!string.IsNullOrEmpty(displayName) && (!m_Names.TryGetValue(FileNameFor(modKey), out var old) || old != displayName))
            {
                m_Names[FileNameFor(modKey)] = displayName;
                WriteAtomic(Path.Combine(RootDir, "mods.json"), JsonConvert.SerializeObject(Sorted(m_Names), Formatting.Indented));
            }
        }

        /// <summary>
        /// 归属规则改进后，同一条文本可能之前被存在别的分组里（如 src_MemorySource）。
        /// 把原文一致的译文复制到正确的 mod 名下，避免重复付费翻译。返回复制的条数。
        /// </summary>
        public int Adopt(string locale, string modKey, string displayName, IReadOnlyDictionary<string, string> sources, IEnumerable<string> keys)
        {
            string target = FileNameFor(modKey);
            var map = GetLocale(locale);
            // 先列出候选来源再修改，避免在遍历字典时新增条目。
            var candidates = map.Where(p => p.Key != target && !p.Key.StartsWith("desc_", StringComparison.Ordinal) && !p.Key.StartsWith("fix_", StringComparison.Ordinal)).ToList();
            ModTranslations data = null;
            int moved = 0;
            foreach (string key in keys)
            {
                foreach (var donor in candidates)
                {
                    if (!donor.Value.Translations.TryGetValue(key, out var translation))
                    {
                        continue;
                    }
                    if (!donor.Value.Sources.TryGetValue(key, out var source) || !sources.TryGetValue(key, out var current) || source != current)
                    {
                        continue;
                    }
                    data = data ?? GetOrCreate(locale, modKey);
                    data.Translations[key] = translation;
                    data.Sources[key] = source;
                    if (donor.Value.Scores.TryGetValue(key, out int score))
                    {
                        data.Scores[key] = score;
                    }
                    // 只复制、不从原文件移除：检测可能不完整（启动时 mod 陆续加载），移走会导致译文丢失或来回搬家。
                    moved++;
                    break;
                }
            }
            if (moved == 0)
            {
                return 0;
            }
            Save(locale, modKey, displayName);
            return moved;
        }

        public bool Delete(string locale, string modKey)
        {
            lock (m_Lock)
            {
                bool removed = GetLocale(locale).Remove(FileNameFor(modKey));
                foreach (string path in new[] { TranslationPath(locale, modKey), SourcePath(locale, modKey), QualityPath(locale, modKey) })
                {
                    try
                    {
                        if (File.Exists(path))
                        {
                            File.Delete(path);
                            removed = true;
                        }
                    }
                    catch (Exception ex)
                    {
                        Mod.Log.Warn("Delete failed " + path + ": " + ex.Message);
                    }
                }
                return removed;
            }
        }

        private static SortedDictionary<string, string> Sorted(Dictionary<string, string> d)
        {
            return new SortedDictionary<string, string>(d, StringComparer.Ordinal);
        }

        private static void WriteAtomic(string path, string content)
        {
            string tmp = path + ".tmp";
            File.WriteAllText(tmp, content, s_Utf8);
            if (File.Exists(path))
            {
                try
                {
                    File.Replace(tmp, path, null);
                    return;
                }
                catch (Exception)
                {
                    // 某些文件系统/运行时不支持 Replace，退回删除后移动。
                    File.Delete(path);
                }
            }
            File.Move(tmp, path);
        }
    }
}
